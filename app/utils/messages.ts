/**
 * メッセージのフォーマット関数
 * @param Type         取得するメッセージの種別
 * @param Key          取得するメッセージのキー
 * @param MessageArray メッセージに埋め込む値
 * @returns            取得したメッセージ(整形済み)
 */
export function messageFormat<
  MessageType extends keyof typeof messages,
  MessageKey extends keyof (typeof messages)[MessageType],
>(Type: MessageType, Key: MessageKey, ...MessageArray: unknown[]): string {
  /* ---------------------------------------------
   *  1. 定義
   * --------------------------------------------- */
  // 1. メッセージを取得
  const GetMessage = messages[Type][Key];

  /* ---------------------------------------------
   *  2. バリデーションチェック
   * --------------------------------------------- */
  // 1. メッセージの取得が行えない場合は空文字を返す
  if (!GetMessage) {
    return '';
  }

  /* ---------------------------------------------
   *  3. 取得したメッセージをフォーマット
   * --------------------------------------------- */
  return MessageArray.reduce((Message: string, SetMessage, Index) => {
    // 1. 呼び出し元で埋め込みメッセージを設定していない場合は空、そうでなければ埋め込みメッセージを保持する
    const ValidateMessage = SetMessage == null ? '' : SetMessage.toString();
    // 2. メッセージの埋め込み箇所を判別する正規表現文字列を作成
    const Pattern = new RegExp(`\\{${Index}\\}`, 'g');
    // 3. 項番2のパターンに一致した箇所に埋め込みメッセージを設定する
    return Message.replace(Pattern, ValidateMessage);
  }, GetMessage as string);
}
